def test_a_key_merely_ending_in_path_is_not_a_path():
    with pytest.raises(ClientConfigError):
        parse("server_commit: c\nprotos:\n  - filepath: /etc/passwd\n    sha256: deadbeef\n")


def test_a_key_merely_ending_in_sha256_is_not_a_checksum():
    with pytest.raises(ClientConfigError):
        parse("server_commit: c\nprotos:\n  - path: a.proto\n    xsha256: FORGED\n")


def test_a_nested_block_cannot_override_an_entrys_checksum():
    p = parse(
        "server_commit: c\n"
        "protos:\n"
        "  - path: a.proto\n"
        "    sha256: REAL\n"
        "    signature:\n"
        "      sha256: FORGED\n"
    )
    assert p.protos[0].sha256 == "REAL"


def test_a_key_named_inside_another_value_is_not_a_key():
    p = parse(
        "server_commit: c\n"
        "protos:\n"
        "  - path: real.proto\n"
        "    sha256: aaa\n"
        "    note: see path: fake.proto\n"
    )
    assert p.protos[0].path == "real.proto"


def test_a_nested_list_does_not_become_extra_records():
    p = parse(
        "server_commit: c\n"
        "protos:\n"
        "  - path: a\n"
        "    sha256: b\n"
        "    deps:\n"
        "      - path: c\n"
        "        sha256: d\n"
    )
    assert [(r.path, r.sha256) for r in p.protos] == [("a", "b")]


def test_a_comment_at_column_zero_does_not_truncate_the_list():
    p = parse(
        "server_commit: c\n"
        "protos:\n"
        "  - path: a\n"
        "    sha256: b\n"
        "# a note\n"
        "  - path: c\n"
        "    sha256: d\n"
    )
    assert [r.path for r in p.protos] == ["a", "c"]


def test_a_hash_inside_quotes_is_not_a_comment():
    p = parse('server_commit: "abc#123"\nprotos:\n  - path: a\n    sha256: b\n')
    assert p.server_commit == "abc#123"


def test_a_block_scalar_is_rejected_rather_than_misread():
    with pytest.raises(ClientConfigError, match="block scalar"):
        parse("server_commit: |\n  abc\nprotos:\n  - path: a\n    sha256: b\n")


def test_a_duplicated_field_in_one_entry_is_rejected():
    with pytest.raises(ClientConfigError, match="twice"):
        parse("server_commit: c\nprotos:\n  - path: a\n    sha256: b\n    sha256: c\n")


def test_crlf_line_endings_parse():
    p = parse("server_commit: c\r\nprotos:\r\n  - path: a\r\n    sha256: b\r\n")
    assert (p.server_commit, p.protos[0].path) == ("c", "a")


def test_the_packaged_licence_matches_the_repository_root():
    # The wheel needs its own copy — a path outside the project root produces a
    # malformed archive entry — so this guards the two against drifting apart.
    packaged = REPO / "python" / "LICENSE"
    root = REPO / "LICENSE"
    assert packaged.read_text() == root.read_text(), (
        "python/LICENSE has drifted from the repository LICENSE; copy it across"
    )

"""The provenance descriptor shipped inside the package."""

import hashlib
import pathlib

import pytest

from memco._provenance import parse, provenance
from memco.errors import ClientConfigError

REPO = pathlib.Path(__file__).resolve().parents[2]


def test_provenance_is_readable_from_the_installed_package():
    p = provenance()
    assert p.server_commit
    assert p.protos
    assert p.protos[0].path == "memco/memory/v1/memory.proto"


def test_provenance_is_cached():
    assert provenance() is provenance()


def test_checksum_matches_the_contract_in_the_repository():
    proto = REPO / "proto" / "memco" / "memory" / "v1" / "memory.proto"
    expected = hashlib.sha256(proto.read_bytes()).hexdigest()
    assert provenance().protos[0].sha256 == expected


def test_parse_reads_the_generated_shape():
    p = parse(
        """
# Generated by the server repository's SDK export. Do not edit.
server_commit: abc123
codegen:
  python:
    grpcio_tools: unknown
requires:
  python:
    grpcio: ">=1.76.0,<2"
protos:
  - path: memco/memory/v1/memory.proto
    sha256: deadbeef
"""
    )
    assert p.server_commit == "abc123"
    assert len(p.protos) == 1
    assert (p.protos[0].path, p.protos[0].sha256) == ("memco/memory/v1/memory.proto", "deadbeef")


def test_nested_keys_cannot_impersonate_the_real_ones():
    # The descriptor nests other languages' sections, several of which use the
    # same key names. Only the top-level commit and the protos list may count.
    p = parse(
        """
codegen:
  nested:
    server_commit: DECOY
    path: decoy.proto
    sha256: decoysha
protos:
  - path: real.proto
    sha256: realsha
server_commit: REAL
"""
    )
    assert p.server_commit == "REAL"
    assert [(r.path, r.sha256) for r in p.protos] == [("real.proto", "realsha")]


@pytest.mark.parametrize(
    "text",
    [
        "codegen:\n  python: {}\n",  # no server_commit
        "server_commit: abc\n",  # no protos
        "server_commit: abc\nprotos:\n  - path: only-a-path\n",  # proto without a checksum
    ],
)
def test_malformed_descriptor_raises_rather_than_guessing(text):
    with pytest.raises(ClientConfigError):
        parse(text)


